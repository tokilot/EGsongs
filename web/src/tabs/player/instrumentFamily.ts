/** Instrument families, each with its own icon and colour so tracks are told apart at a glance. */
export type InstrumentFamily =
  | 'acoustic'
  | 'electric'
  | 'distortion'
  | 'bass'
  | 'drums'
  | 'keys'
  | 'organ'
  | 'bells'
  | 'strings'
  | 'voice'
  | 'brass'
  | 'wind'
  | 'synth'
  | 'pad'
  | 'ethnic'
  | 'effects'

export function instrumentFamily(program: number, isPercussion: boolean): InstrumentFamily {
  if (isPercussion) return 'drums'
  if (program <= 7) return 'keys'
  if (program <= 15) return 'bells'
  if (program <= 23) return 'organ'
  if (program <= 25) return 'acoustic'
  if (program === 29 || program === 30) return 'distortion'
  if (program <= 31) return 'electric'
  if (program <= 39) return 'bass'
  if (program <= 51) return program === 47 ? 'drums' : 'strings'
  if (program <= 54) return 'voice'
  if (program === 55) return 'strings'
  if (program <= 63) return 'brass'
  if (program <= 79) return 'wind'
  if (program <= 87) return 'synth'
  if (program <= 95) return 'pad'
  if (program <= 103) return 'effects'
  if (program <= 111) return program === 105 || program === 104 || program === 106 ? 'acoustic' : 'ethnic'
  if (program <= 119) return program <= 112 ? 'bells' : 'drums'
  return 'effects'
}
